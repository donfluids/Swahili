export type StringKey = keyof typeof en;

const TABLES: Record<Language, Record<StringKey, string>> = { sw, en };

export function translate(language: Language, key: StringKey, params?: Record<string, string | number>): string {
  let text = TABLES[language][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

/** Returns t(key, params) for the interface language in settings. */
export function useT(): (key: StringKey, params?: Record<string, string | number>) => string {
  const display = useDisplaySettings();
  if (!display) throw new Error('useT must be used inside SettingsProvider');
  const lang = display.language;
  return useCallback((key: StringKey, params?: Record<string, string | number>) => translate(lang, key, params), [lang]);
}

// The Swahili Bibles' names: in Swahili as their publishers give them, and in English.
const SWAHILI_NAMES: Record<string, { sw: string; en: string; short: string }> = {
  SWU: { sw: 'Biblia Takatifu (ULB)', en: 'Swahili Unlocked Literal Bible', short: 'ULB' },
  SWN: { sw: 'Neno: Bibilia Takatifu 2015', en: 'Neno 2015 (Kiswahili Contemporary Version)', short: 'Neno' },
  SWM: { sw: 'Neno: Maandiko Matakatifu 2024', en: 'Neno 2024 (Maandiko Matakatifu)', short: 'Neno 2024' },
};

/** Heading for how a translation renders a word: "In the KJV", "Katika ULB". */
export function renderingsLabel(language: Language, id: string): string {
  return language === 'sw' ? `Katika ${shortName(id)}` : `In the ${shortName(id)}`;
}

/** A translation's short name in running text and on the Bible switch: "ULB", "Neno", "KJV". */
export function shortName(id: string): string {
  return SWAHILI_NAMES[id]?.short ?? id;
}

/** A Swahili Bible's own name. */
export const NATIVE_BIBLE_NAME: Partial<Record<string, string>> = Object.fromEntries(Object.entries(SWAHILI_NAMES).map(([id, n]) => [id, n.sw]));

/** A Bible's name where its text is read: a Swahili Bible by its own name, the English ones by their English names. */
export function bibleName(language: Language, id: string): string {
  return NATIVE_BIBLE_NAME[id] ?? translationName(language, id);
}

/** A Bible's name in English, for a detail line under its own name. */
export function englishName(id: string): string {
  return SWAHILI_NAMES[id]?.en ?? translationName('en', id);
}

export function translationName(language: Language, id: string): string {
  const swahili = SWAHILI_NAMES[id];
  if (swahili) return language === 'sw' ? swahili.sw : swahili.en;
  if (id === 'KJV') return 'King James Version';
  if (id === 'BSB') return 'Berean Standard Bible';
  return id;
}
